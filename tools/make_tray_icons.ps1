# Generates src/app/platform/tray_icons.h from the two PNG assets.
#
# The Linux tray (StatusNotifierItem) publishes its icon as a raw ARGB32 pixmap
# because there is no portable image decoder on that path: the desktop shell
# reads the pixels straight from the D-Bus property. This script downsamples the
# source artwork (assets/white_sound.png and assets/white_sound_off.png) to the
# small size a tray wants and writes the bytes as a C++ header.
#
# The generated header is committed, so building the app does not require
# PowerShell; re-run this only when the artwork changes.
#
#   powershell -ExecutionPolicy Bypass -File tools\make_tray_icons.ps1

param(
    [string]$AssetsDir = (Join-Path $PSScriptRoot '..\assets'),
    [string]$Output    = (Join-Path $PSScriptRoot '..\src\app\platform\tray_icons.h'),
    [int]$Size         = 24
)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

function New-ScaledBitmap {
    param([string]$Path, [int]$Size)
    $src = [System.Drawing.Image]::FromFile($Path)
    $bmp = New-Object System.Drawing.Bitmap($Size, $Size,
        [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
    $g.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
    $g.Clear([System.Drawing.Color]::Transparent)
    $g.DrawImage($src, 0, 0, $Size, $Size)
    $g.Dispose()
    $src.Dispose()
    return $bmp
}

# Emits the pixels row-major as A,R,G,B (the network byte order the
# StatusNotifierItem IconPixmap property expects).
function Emit-ArgbArray {
    param([System.Drawing.Bitmap]$Bmp, [string]$Name, [int]$Size)
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine("inline constexpr unsigned char $Name[$($Size * $Size * 4)] = {")
    for ($y = 0; $y -lt $Size; $y++) {
        $line = New-Object System.Text.StringBuilder
        [void]$line.Append('    ')
        for ($x = 0; $x -lt $Size; $x++) {
            $c = $Bmp.GetPixel($x, $y)
            [void]$line.Append(('0x{0:X2},0x{1:X2},0x{2:X2},0x{3:X2},' -f $c.A, $c.R, $c.G, $c.B))
        }
        [void]$sb.AppendLine($line.ToString())
    }
    [void]$sb.AppendLine('};')
    return $sb.ToString()
}

$on = New-ScaledBitmap (Join-Path $AssetsDir 'white_sound.png') $Size
$off = New-ScaledBitmap (Join-Path $AssetsDir 'white_sound_off.png') $Size

$header = New-Object System.Text.StringBuilder
[void]$header.AppendLine('// Generated by tools/make_tray_icons.ps1 -- do not edit by hand.')
[void]$header.AppendLine('//')
[void]$header.AppendLine('// ARGB32 pixmaps (network byte order: A, R, G, B) for the Linux tray icon,')
[void]$header.AppendLine("// downsampled to $($Size)x$Size from assets/white_sound*.png.")
[void]$header.AppendLine('')
[void]$header.AppendLine('#pragma once')
[void]$header.AppendLine('')
[void]$header.AppendLine('namespace ws {')
[void]$header.AppendLine('namespace platform {')
[void]$header.AppendLine('')
[void]$header.AppendLine("inline constexpr int kTrayIconWidth = $Size;")
[void]$header.AppendLine("inline constexpr int kTrayIconHeight = $Size;")
[void]$header.AppendLine('')
[void]$header.AppendLine('// Emitting (active): the lit cyan/blue badge.')
[void]$header.Append((Emit-ArgbArray $on 'kTrayIconOnArgb' $Size))
[void]$header.AppendLine('')
[void]$header.AppendLine('// Inactive: the dark unlit badge.')
[void]$header.Append((Emit-ArgbArray $off 'kTrayIconOffArgb' $Size))
[void]$header.AppendLine('')
[void]$header.AppendLine('} // namespace platform')
[void]$header.AppendLine('} // namespace ws')

$on.Dispose()
$off.Dispose()

[System.IO.File]::WriteAllText($Output, $header.ToString())
Write-Host "Wrote $Output ($((Get-Item $Output).Length) bytes)"
